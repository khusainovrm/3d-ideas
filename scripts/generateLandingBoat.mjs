import sharp from 'sharp'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const directory = new URL('../src/experiments/landing/', import.meta.url)
const source = fileURLToPath(new URL('assets/boat.png', directory))
const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
let left = info.width, top = info.height, right = -1, bottom = -1
for (let y = 0; y < info.height; y++) {
  for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] <= 2) continue
    left = Math.min(left, x); right = Math.max(right, x)
    top = Math.min(top, y); bottom = Math.max(bottom, y)
  }
}
if (right < left) throw new Error('Boat image is empty')
// Keep an alpha margin for filtering around the thin mast and hull outline.
const padding = 16
left = Math.max(0, left - padding); top = Math.max(0, top - padding)
right = Math.min(info.width - 1, right + padding); bottom = Math.min(info.height - 1, bottom + padding)
const crop = { left, top, width: right - left + 1, height: bottom - top + 1 }
const output = await sharp(source).extract(crop).webp({ lossless: true, effort: 6 })
  .toFile(fileURLToPath(new URL('assets/boat.generated.webp', directory)))
writeFileSync(new URL('boat.generated.ts', directory), `// Generated by npm run generate:landing-boat.\nexport const BOAT_IMAGE = ${JSON.stringify({ width: output.width, height: output.height, crop, waterlineFromBottom: 0.06 }, null, 2)} as const\n`)
console.log(`Boat: ${info.width}×${info.height} → ${output.width}×${output.height}, ${output.size} bytes`)
