import sharp from 'sharp'
import { writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'

const directory = new URL('../src/experiments/landing/', import.meta.url)
const images = [
  { source: 'dots3', constant: 'LANDING_PARTICLE_QUALITY', levels: [
    ['low', 768, 35000, 'particles-low.generated.bin'],
    ['medium', 1600, 95000, 'particles-medium.generated.bin'],
    ['high', 3840, 450000, 'particles-dots3.generated.bin'],
  ] },
  { source: 'mountans', constant: 'MOUNTAIN_PARTICLE_QUALITY', levels: [
    ['low', 600, 35000, 'mountains-low.generated.bin'],
    ['medium', 1280, 100000, 'mountains-medium.generated.bin'],
    ['high', 3840, 650000, 'mountains-high.generated.bin'],
  ] },
]
const exports = []
for (const image of images) {
  const metadata = {}
  for (const [key, width, budget, file] of image.levels) {
    const { data, info } = await sharp(fileURLToPath(new URL(`assets/${image.source}.png`, directory)))
      .flatten({ background: '#000000' }).resize({ width, withoutEnlargement: true })
      .greyscale().raw().toBuffer({ resolveWithObject: true })
    const records = []
    let previousIndex = 0
    let count = 0
    for (let index = 0; index < data.length; index++) {
      const light = data[index]
      if (light <= 1) continue
      // Unsigned LEB128 pixel-index delta followed by exact luminance.
      let delta = index - previousIndex
      previousIndex = index
      while (delta >= 128) { records.push((delta & 127) | 128); delta >>>= 7 }
      records.push(delta, light)
      count++
    }
    if (count > budget) throw new Error(`${image.source}/${key} budget exceeded: ${count} > ${budget}`)
    const header = Buffer.alloc(16)
    header.write('LPT1')
    header.writeUInt32LE(info.width, 4)
    header.writeUInt32LE(info.height, 8)
    header.writeUInt32LE(count, 12)
    const packed = gzipSync(Buffer.concat([header, Buffer.from(records)]), { level: 9 })
    writeFileSync(new URL(file, directory), packed)
    metadata[key] = { width: info.width, height: info.height, count, bytes: packed.length }
    console.log(`${image.source}/${key}: ${count} particles, ${packed.length} bytes`)
  }
  exports.push(`export const ${image.constant} = ${JSON.stringify(metadata, null, 2)} as const`)
}
writeFileSync(new URL('particles.generated.ts', directory),
  `// Generated by npm run generate:landing-particles.\n${exports.join('\n')}\n`)
